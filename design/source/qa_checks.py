import os
from pathlib import Path
import json
from render_design import markup
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
results=[]
def save(): (ROOT/'qa/interaction-checks.json').write_text(json.dumps(results,ensure_ascii=False,indent=2))
def check(name,cond):
 results.append({'test':name,'pass':bool(cond)});save();print(('PASS ' if cond else 'FAIL ')+name,flush=True)
with sync_playwright() as w:
 b=w.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),headless=True,args=['--no-sandbox'])
 c=b.new_context(viewport={'width':390,'height':844},locale='ru-RU')
 p=c.new_page();p.set_default_timeout(3500)
 def load(id):
  p.set_content(markup(id,export=False));p.wait_for_function('window.KOREN_READY===true')
  p.evaluate("document.querySelector('.prototype-banner')?.remove()")
 def choose(selector):p.locator(selector).locator('..').click()
 load('D06')
 check('Связи отчёта: ничего не отмечено автоматически',p.locator('[data-link-check]:checked').count()==0)
 check('До выбора связь не подтверждается',p.locator('[data-links-next]').is_disabled())
 choose('input[value="light"]')
 check('Ручной выбор света включает следующий шаг',p.locator('[data-links-next]').is_enabled())
 p.locator('[data-links-next]').click()
 check('Открыто отдельное подтверждение D07',p.evaluate('KOREN_APP.getScreen()')=='D07')
 check('Дверь явно не затрагивается','Дверь не затрагивается' in p.locator('body').inner_text())
 p.locator('button[data-go="D08"]').click()
 check('После связи нет авторских кнопок у диспетчера',p.evaluate('KOREN_APP.getScreen()')=='D08' and p.locator('input[name="observation"]').count()==0)
 load('X04')
 check('Ручной путь при недоступности подсказки',p.locator('[data-link-check]').count()==2 and p.locator('[data-link-check]:checked').count()==0)
 load('A12');choose('input[value="unable"]')
 check('Все три наблюдения доступны',p.locator('input[name="observation"]').count()==3)
 p.locator('[data-action="observation"]').click()
 check('Не могу проверить не превращается в положительный результат',p.evaluate('KOREN_APP.getScreen()')=='X09' and 'Пока не удалось проверить' in p.locator('body').inner_text())
 load('A13')
 check('Свет и дверь остаются двумя отдельными пунктами',p.locator('.problem').count()==2 and p.locator('.problem.success').count()==1)
 check('Дверь не получила успешный статус',not p.locator('.problem').filter(has_text='Не закрывается дверь').evaluate("el => el.classList.contains('success')"))
 load('A18')
 check('Отзыв не превратился в 100 процентов выполнения','100%' not in p.locator('body').inner_text() and '1 отозван' in p.locator('h1').inner_text())
 load('D03');p.locator('button[data-go="D04"]').click();p.locator('button[data-go="D08"]').click()
 check('Сохранение плана не создаёт вымышленного отчёта','Лампу заменили' not in p.locator('body').inner_text())
 load('A09');p.locator('[data-go="A15"]').click()
 check('Ранняя история не показывает будущий отчёт','Лампу заменили' not in p.locator('body').inner_text())
 load('A14');p.locator('[data-go="A15"]').click()
 check('История двери не приписывает ей отчёт про свет','Лампу заменили' not in p.locator('body').inner_text())
 load('A03');p.locator('[name="appeal-description"]').fill('Текст сохраняется при смене оформления')
 p.locator('[aria-label="Настройки"]').click();choose('input[data-pref="theme"][value="dark"]')
 check('Тёмная тема применяется сразу',p.locator('html').get_attribute('data-theme')=='dark')
 choose('input[data-pref="text"][value="large"]')
 check('Крупный текст меняет размер, а не изображение',p.evaluate('parseFloat(getComputedStyle(document.documentElement).fontSize)')==20)
 p.locator('[data-back]').click()
 check('Смена темы не стирает ввод',p.locator('[name="appeal-description"]').input_value()=='Текст сохраняется при смене оформления')
 load('M08');text=p.locator('body').inner_text()
 check('Недоступная карточка не раскрывает дом и номер','Садовая' not in text and '124' not in text and 'Анна' not in text)
 p.set_content(markup('R01'));p.wait_for_function('window.KOREN_READY===true')
 check('R01: заголовок увеличен ровно до 54 px',p.locator('h1').evaluate('el => parseFloat(getComputedStyle(el).fontSize)')==54)
 check('R01: основной текст 36 px',p.locator('body').evaluate('el => parseFloat(getComputedStyle(el).fontSize)')==36)
 p.set_content(markup('C03'));p.wait_for_function('window.KOREN_READY===true')
 check('C03: три выбора темы видны в каждой колонке',all(p.locator(f'.component-theme[data-theme="{t}"] .theme-options input:checked').count()==3 for t in ['light','dark']))
 b.close()
print('INTERACTION CHECKS',sum(x['pass'] for x in results),'/',len(results),flush=True)
